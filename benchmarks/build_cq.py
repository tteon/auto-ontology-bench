def person_display(edgar_name: str) -> str:
    """EDGAR 'MUSK ELON' / 'Malave Jesus Jr' -> 'Elon Musk' / 'Jesus Malave Jr'."""
    parts = edgar_name.split()
    suffix = [p for p in parts[1:] if p.rstrip(".").lower() in ("jr", "sr", "ii", "iii", "iv")]
    rest = [p for p in parts[1:] if p not in suffix]
    return " ".join(w.capitalize() if w.isupper() or w.islower() else w for w in rest + parts[:1] + suffix)


def fm(var: str, t: str, code: str, year: str) -> str:
    """Cypher pattern for one FY metric value of a company."""
    return (f"(c:Company {{ticker: '{t}'}})-[:REPORTED]->({var}:FinancialMetric {{fiscal_year: {year}, fiscal_period: 'FY'}})"
            f"-[:OF_METRIC]->(:MetricDefinition {{metric_code: '{code}'}})")


