TIER5_CONCEPTS = [
    "total Scope 1 and Scope 2 carbon emissions", "number of full-time employees", "closing share price on its last trading day of the year",
    "S&P long-term credit rating", "customer satisfaction score", "number of patents granted", "CEO's total annual compensation",
    "market share in its main business segment", "average analyst price target", "ESG risk score",
]
TIER5_FORMS = [
    "What was {name}'s {concept} in fiscal year 2024?",
    "Report {name}'s {concept} for 2025.",
    "How did {name}'s {concept} change between 2023 and 2024?",
    "Which is higher: {name}'s {concept} or its closest peer's?",
    "Give {name}'s most recent {concept}.",
]


def tier5(rng: random.Random) -> list[dict[str, Any]]:
    out = []
    tickers = list(NAMES)
    for k, concept in enumerate(TIER5_CONCEPTS):
        for j, form in enumerate(TIER5_FORMS):
            t = tickers[(k + j * 3) % len(tickers)]
            out.append({"template": "t5_unanswerable", "tier": 5, "params": [t, concept],
                        "question": form.format(name=NAMES[t], concept=concept), "answerable": False,
                        "gold_sql": None, "gold_cypher": None, "ordered": False, "gold_rows": None})
    rng.shuffle(out)
    return out


def _clean(rows: list[tuple]) -> list[list[Any]]:
    def conv(v: Any) -> Any:
        if hasattr(v, "isoformat"):
            return v.isoformat()
        if hasattr(v, "to_native"):
            return conv(v.to_native())
        if isinstance(v, (int, float, str, bool)) or v is None:
            return v
        if isinstance(v, (list, tuple)):
            return [conv(x) for x in v]
        return float(v) if re.fullmatch(r"-?\d+(\.\d+)?", str(v)) else str(v)
    return [[conv(v) for v in r] for r in rows]


async def build() -> None:
    rng = random.Random(20261115)
    pg, neo = PgExecutor("finder_real", 4), NeoExecutor(4)
    await pg.start()
    await neo.start()
    by_tier: dict[int, dict[str, list[dict]]] = defaultdict(lambda: defaultdict(list))
    report = []
    for tpl in templates():
        res = await pg.run(tpl["params"])
        combos = [tuple(str(x) for x in r) for r in res.get("rows") or []]
        rng.shuffle(combos)
        kept = tried = 0
        for combo in combos:
            if kept >= tpl.get("cap", 10):
                break
            tried += 1
            sql, cy = tpl["sql"](*combo), tpl["cy"](*combo)
            a, b = await pg.run(sql), await neo.run(cy)
            ordered = "ORDER BY" in sql.upper() and "LIMIT" not in sql.upper()
            if not (a.get("ok") and b.get("ok") and a["rows"] and strict_equal(a["rows"], b["rows"], ordered)):
                if a.get("ok") and b.get("ok") and a["rows"] and not strict_equal(a["rows"], b["rows"]):
                    report.append({"template": tpl["id"], "params": combo, "issue": "pg/neo mismatch",
                                   "pg": _clean(a["rows"][:3]), "neo": _clean(b["rows"][:3])})
                continue
            kept += 1
            by_tier[tpl["tier"]][tpl["id"]].append({
                "template": tpl["id"], "tier": tpl["tier"], "params": list(combo), "question": tpl["q"](*combo),
                "answerable": True, "gold_sql": sql, "gold_cypher": cy, "ordered": ordered, "gold_rows": _clean(a["rows"]),
                "gold_pg_ms": round(a["server_ms"], 2), "gold_neo_server_ms": b["server_ms"],
            })
        print(f"{tpl['id']:28} tier {tpl['tier']}  kept {kept:2d} / tried {tried:3d} (pool {len(combos)})")
    await pg.close()
    await neo.close()

    items: list[dict] = []
    for tier in (1, 2, 3, 4):
        pools = {k: v[:] for k, v in by_tier[tier].items()}
        chosen: list[dict] = []
        while len(chosen) < PER_TIER and any(pools.values()):  # round-robin across templates
            for k in sorted(pools):
                if pools[k] and len(chosen) < PER_TIER:
                    chosen.append(pools[k].pop(0))
        items += chosen
        print(f"tier {tier}: {len(chosen)} items from {len(by_tier[tier])} templates")
    items += tier5(rng)[:PER_TIER]

    # stratified dev/test split: every 5th item of each template (in shuffled order) goes to dev, up to DEV_PER_TIER
    per_tier_dev: dict[int, int] = defaultdict(int)
    seen_tpl: dict[str, int] = defaultdict(int)
    for it in items:
        idx = seen_tpl[it["template"]]
        seen_tpl[it["template"]] += 1
        dev = idx % 5 == 0 and per_tier_dev[it["tier"]] < DEV_PER_TIER
        per_tier_dev[it["tier"]] += dev
        it["split"] = "dev" if dev else "test"
    for t in (1, 2, 3, 4, 5):  # top up dev to exactly DEV_PER_TIER
        for it in items:
            if per_tier_dev[t] >= DEV_PER_TIER:
                break
            if it["tier"] == t and it["split"] == "test":
                it["split"] = "dev"
                per_tier_dev[t] += 1
    for n, it in enumerate(items):
        it["cq_id"] = f"cq{it['tier']}_{n:03d}"
        it["review"] = "pending-human-review"
    out = ROOT / "benchmarks" / "cq_dataset.jsonl"
    out.write_text("\n".join(json.dumps(it, ensure_ascii=False) for it in items) + "\n")
    (ROOT / "results" / "cq_build_report.json").write_text(json.dumps(report, indent=1, ensure_ascii=False))
    print(f"wrote {len(items)} items -> {out}; dev per tier {dict(per_tier_dev)}; pg/neo mismatches logged: {len(report)}")


if __name__ == "__main__":
    asyncio.run(build())
